function outline(start){
  const points=[start];
  return {points,line(x,y){points.push([x,y]);return this;},curve(a,b,end,steps){
    const from=points.at(-1);
    for(let i=1;i<=steps;i++){
      const t=i/steps,u=1-t;
      points.push([0,1].map(k=>u*u*u*from[k]+3*u*u*t*a[k]+3*u*t*t*b[k]+t*t*t*end[k]));
    }
    return this;
  }};
}
function symmetric(half){
  const points=[...half,...half.slice(1,-1).reverse().map(([x,y])=>[1-x,y])];
  const minimum=Math.min(...points.map(p=>p[1])),maximum=Math.max(...points.map(p=>p[1]));
  const left=Math.min(...points.map(p=>p[0])),right=Math.max(...points.map(p=>p[0]));
  assert.ok(points.length<=66,'Presets must remain within 64 triangles');
  return points.map(([x,y])=>[Number(((x-left)/(right-left)).toFixed(8)),Number(((y-minimum)/(maximum-minimum)).toFixed(8))]);
}
