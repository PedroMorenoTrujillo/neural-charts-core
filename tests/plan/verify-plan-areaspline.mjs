import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
import {planChart} from '../../dist/plan.js';
const axes={x:{kind:'category',values:['a','b','c','d','e'].map(id=>({id,label:id}))},y:{kind:'linear'}};
const spec={family:'areaspline',title:'Measured area',axes,series:[{id:'r',name:'Reading',data:[2,8,null,-3,5].map((y,i)=>({id:String(i),x:axes.x.values[i].id,y}))}]};
const size={width:320,height:280};
const result=planChart(spec,size);assert.equal(result.status,'ok');
const line=planChart({...spec,family:'spline'},size);assert.equal(line.status,'ok');
const frame=result.frame,mark=frame.series[0];
assert.deepEqual(mark.commands,line.frame.series[0].commands);
assert.equal(mark.areaCommands.filter(c=>c.kind==='M').length,2);
assert.equal(mark.areaCommands.filter(c=>c.kind==='Z').length,2);
assert.equal(frame.observations.length,4);assert(frame.observations.some(p=>p.value===-3));
const curved=planChart({...spec,series:[{...spec.series[0],data:[2,8,4,12,5].map((y,i)=>({id:String(i),x:axes.x.values[i].id,y}))}]},size);
assert.equal(curved.status,'ok');assert(curved.frame.series[0].commands.length>6,'Genuine flattened smooth outline');
assert.equal(planChart({...spec,axes:{...axes,y:{kind:'linear',includeZero:false}}},size).status,'invalid');
assert.equal(planChart({...spec,series:[{...spec.series[0],curve:'step-after'}]},size).status,'invalid');
const stacked=planChart(spec,{...size,stacking:'sum'});assert.equal(stacked.status,'ok');assert.equal(stacked.frame.family,'areaspline');assert(stacked.frame.series[0].areaCommands.length>5);
assert.equal(planChart(spec,{...size,stacking:'percent'}).status,'invalid','The existing nonnegative percent contract remains enforced');
assert.equal(planChart(spec,{...size,hiddenSeriesIds:['r']}).status,'empty');
assert.equal(planChart(spec,{...size,references:[{id:'threshold',axis:'y',value:0}]}).status,'ok');
assert.equal(planChart(spec,{...size,viewport:{axes:'x',value:{x:{firstId:'d',lastId:'e'}}}}).status,'ok');
assert(Object.isFrozen(mark.areaCommands));
await writeFile('work/reports/core-plan-areaspline-current.json',JSON.stringify({status:'passed',checks:8,scope:'Real smooth outline/fill, gap topology, signed zero baseline, strict fixed shape, visibility, references, viewport and deep ownership.'},null,2)+'\n');
console.log('PASS 8 smooth area contract checks');
